function results=run_tests_v2()
%RUN_TESTS_V2 Physics/regression checks for the component model.
cfg=default_config_v2(); input=dchr.make_inputs(cfg); out=dchr.simulate_system_v2(cfg,input);
tol=1e-8;
networkFromHP=out.HP_Heat_Used_MW-out.Storage_Charge_MW;
balanceResidual=out.Heat_Demand_MW-(networkFromHP+out.Storage_Discharge_MW+out.Gas_Heat_MW);
checks={ ...
 'district_heat_balance', max(abs(balanceResidual))<1e-6; ...
 'storage_lower_bound', min(out.Storage_E_MWh)>=-tol; ...
 'storage_upper_bound', max(out.Storage_E_MWh)<=cfg.storage.capacity_MWh+tol; ...
 'cop_lower_bound', min(out.COP)>=cfg.hp.cop_min-tol; ...
 'cop_upper_bound', max(out.COP)<=cfg.hp.cop_max+tol; ...
 'hp_source_not_overdrawn', max(out.HP_Source_Used_MW-out.HX_Heat_to_HP_MW)<=1e-6; ...
 'nonnegative_gas', min(out.Gas_Heat_MW)>=-tol; ...
 'nonnegative_hp_power', min(out.HP_Electric_MW)>=-tol};
results=cell2table(checks,'VariableNames',{'Test','Passed'});
rootDir=fileparts(fileparts(mfilename('fullpath')));
writetable(results,fullfile(rootDir,'results','tests_v2.csv'));
disp(results);
if ~all(results.Passed), error('DCHR:v2Tests','One or more v0.2 physics checks failed.'); end
end
