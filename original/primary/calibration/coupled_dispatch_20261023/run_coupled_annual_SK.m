% Reprodukovatelny rocny experiment. Bazenska vetva vo vlastnom pracovnom priestore.
here=fileparts(mfilename('fullpath'));
root=fileparts(fileparts(here));
addpath(fullfile(root,'matlab'));addpath(here);
wPath=fullfile(root,'calibration','standards_20261023','official_datasets',...
  'weather_2025_BRATISLAVA_NASA_POWER_hourly_UTC.csv');
w=readtable(wPath);assert(height(w)==8760);
cfg=dchr_config_real_2025_SK();
inp=dchr.make_inputs(cfg);
inp.outdoor_temp_C=w.T2M_C;
assert(all(isfinite(inp.outdoor_temp_C)));
cases=[...
 struct('id','liquid35_without_pool','source',35,'mode',"DIRECT",'pool',false),...
 struct('id','liquid35_direct_pool','source',35,'mode',"DIRECT",'pool',true),...
 struct('id','air25_without_pool','source',25,'mode',"HP",'pool',false),...
 struct('id','air25_hp_pool','source',25,'mode',"HP",'pool',true)];
R=struct([]); All={};
for i=1:numel(cases)
    c=cfg;c.dc.source_temp_C=cases(i).source;
    cc=cases(i);
    [o,m]=simulate_coupled_pool_SK(c,inp,'poolEnabled',cc.pool,...
      'poolMode',cc.mode,'source_C',cc.source);
    m.case=cc.id;m.mode=char(cc.mode);m.source_temperature_C=cc.source;
    m.model_pue=c.dc.pue;m.model_year=2025;
    m.electricity_2025_EUR_MWh=152.0726027397;
    m.gas_2025_EUR_MWh=55.6347945205;
    m.operating_cost_EUR=(m.gas_heat_MWh/0.9)*m.gas_2025_EUR_MWh+...
       (m.dh_hp_electric_MWh+m.pool_electric_MWh)*m.electricity_2025_EUR_MWh;
    R=[R;m];
    All{i}=o;
    writetable(o,fullfile(here,[cc.id '_8760h.csv']));
    fprintf('COUPLED_CASE %s SOURCE=%0.3fMWh POOL=%0.3fMWh GAS=%0.3fMWh Tmax=%0.3fC\n',...
       cc.id,m.total_source_used_MWh,m.pool_heat_MWh,m.gas_heat_MWh,m.pool_max_C);
end
% Independent regression: zero-pool branch reproduces original dispatch exactly.
for i=[1,3]
    c=cfg;c.dc.source_temp_C=cases(i).source;
    ref=dchr.simulate_system(c,inp);
    cmp=All{i};
    tol=1e-8;
    assert(max(abs(cmp.Gas_Q_MW-ref.Gas_Heat_MW))<tol,'GAS_REGRESSION');
    assert(max(abs(cmp.DH_HP_Q_MW-ref.HP_Heat_Used_MW))<tol,'HEATPUMP_REGRESSION');
    assert(max(abs(cmp.TES_E_MWh-ref.Storage_E_MWh))<tol,'TES_REGRESSION');
    assert(max(abs(cmp.DH_HP_El_MW-ref.HP_Electric_MW))<tol,'ELECTRICITY_REGRESSION');
end
assert(R(2).pool_heat_MWh>R(2).pool_loss_MWh);
assert(R(4).pool_electric_MWh>0);
assert(R(2).pool_electric_MWh==0);
assert(R(2).pool_max_temp_screening_pass && R(4).pool_max_temp_screening_pass);
assert(abs(R(2).pool_energy_residual_MWh)<1e-5);
assert(abs(R(4).pool_energy_residual_MWh)<1e-5);
S=table(string({R.case})',string({R.mode})',[R.source_temperature_C]',...
 [R.dh_demand_MWh]',[R.pool_heat_MWh]',[R.pool_source_MWh]',...
 [R.pool_electric_MWh]',[R.dh_source_used_MWh]',[R.total_source_used_MWh]',...
 [R.source_utilization]',[R.gas_heat_MWh]',[R.dh_hp_electric_MWh]',...
 [R.ERF_source_proxy]',[R.pool_max_C]',[R.pool_energy_residual_MWh]',...
 [R.operating_cost_EUR]',...
 'VariableNames',{'Scenario','PoolMode','Source_C','DH_Demand_MWh',...
 'PoolHeat_MWh','PoolSource_MWh','PoolEl_MWh','DH_Source_MWh',...
 'TotalDCReuseSource_MWh','SourceUtilization','GasHeat_MWh',...
 'DH_HPEl_MWh','ERF_SourceProxy','PoolMaxTemp_C','PoolBalanceResidual_MWh','OPEX_EUR'});
writetable(S,fullfile(here,'coupled_scenarios_2025.csv'));
% Incremental savings relative to gas heating of the same pool thermal profile.
extraGas35=R(2).gas_heat_MWh-R(1).gas_heat_MWh;
extraDHpower35=R(2).dh_hp_electric_MWh-R(1).dh_hp_electric_MWh;
poolGasAvoided35=R(2).pool_heat_MWh/0.9*R(2).gas_2025_EUR_MWh;
netValue35=poolGasAvoided35-extraGas35/0.9*R(2).gas_2025_EUR_MWh ...
  -extraDHpower35*R(2).electricity_2025_EUR_MWh;
extraGas25=R(4).gas_heat_MWh-R(3).gas_heat_MWh;
extraDHpower25=R(4).dh_hp_electric_MWh-R(3).dh_hp_electric_MWh;
poolGasAvoided25=R(4).pool_heat_MWh/0.9*R(4).gas_2025_EUR_MWh;
netValue25=poolGasAvoided25-extraGas25/0.9*R(4).gas_2025_EUR_MWh ...
 -(extraDHpower25+R(4).pool_electric_MWh)*R(4).electricity_2025_EUR_MWh;
summary=struct('year',2025,'location','Bratislava',...
 'weather_data','NASA POWER 2025 hourly reanalysis',...
 'pool_type','25x12.5x1.6m; simulated public swimming, NOT competition certified',...
 'source_heat_metered',false,'legal_compliance_verified',false,...
 'main_dispatch_core_regression_verified',true,...
 'source_boundary_proxy_only',true,'pool_heatpump_COP_assumption',4,...
 'thermal_room_profile','Tair 29C, RH60%, night cover assumed',...
 'source_allocation','5min peak reservation, hourly DH; conservative',...
 'energy_prices','Eurostat SK 2025 X_VAT nonhousehold band averages',...
 'scenario_count',numel(cases),...
 'cases',R,'incremental_value_direct_EUR',netValue35,...
 'incremental_value_hp_EUR',netValue25,...
 'baseline_gas_counterfactual_heat_MWh',R(2).pool_heat_MWh);
fid=fopen(fullfile(here,'coupled_results_2025.json'),'w','n','UTF-8');assert(fid>0);
fprintf(fid,'%s',jsonencode(summary,PrettyPrint=true));fclose(fid);
% Plot is an additional deliverable, not validation.
f=figure('Visible','off','Color','w','Position',[50 60 1120 650]);
tiledlayout(2,1,'Padding','compact');
nexttile;plot(All{2}.Time,All{2}.Pool_T_C,'LineWidth',1);hold on;
plot(All{4}.Time,All{4}.Pool_T_C,'LineWidth',1);
yline(28,'r--','Max swimming pool published');grid on;
ylabel('Teplota bazena [C]');legend('35C priame','25C TC','Limit','Location','best');
title('Rocna dynamika bazena: DC tepelný zdroj');
nexttile;bar(categorical(S.Scenario),[S.PoolSource_MWh S.DH_Source_MWh],'stacked');
ylabel('Rocne vyuzitie odpadoveho tepla [MWh]');grid on;
legend('Bazen','Teplovodna siet','Location','best');
exportgraphics(f,fullfile(here,'coupled_annual_SK.png'),'Resolution',160);
close(f);
disp('COUPLED_DISPATCH_ANNUAL_VERIFIED');
