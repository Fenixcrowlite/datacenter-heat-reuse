% Parametricke varianty nezavisleho integracneho modelu.
here=fileparts(mfilename('fullpath'));root=fileparts(fileparts(here));
addpath(fullfile(root,'matlab'));addpath(here);
cfg=dchr_config_real_2025_SK();
w=readtable(fullfile(root,'calibration','standards_20261023','official_datasets',...
 'weather_2025_BRATISLAVA_NASA_POWER_hourly_UTC.csv'));
i=dchr.make_inputs(cfg);i.outdoor_temp_C=w.T2M_C;
tests=[struct('name','base_500_cover','L',25,'W',12.5,'D',1.6,'cover',true),...
 struct('name','large_1000_cover','L',25,'W',20,'D',2,'cover',true),...
 struct('name','base_500_uncovered','L',25,'W',12.5,'D',1.6,'cover',false)];
outrows={};
for k=1:numel(tests)
 x=tests(k);
 [o,m]=simulate_coupled_pool_SK(cfg,i,'poolEnabled',true,'poolMode',"DIRECT",...
   'source_C',35,'poolLength_m',x.L,'poolWidth_m',x.W,'poolDepth_m',x.D,...
   'coverAtNight',x.cover);
 outrows{k}=table(string(x.name),m.pool_volume_m3,m.pool_area_m2,...
   m.pool_UA_scenario_W_K,m.pool_heat_MWh,m.pool_loss_MWh,...
   m.pool_end_C,m.pool_max_C,m.pool_energy_residual_MWh,...
   m.gas_heat_MWh,m.source_utilization,m.ERF_source_proxy,...
   'VariableNames',{'Scenario','Volume_m3','Surface_m2','UA_scenario_W_K',...
    'PoolHeat_MWh','PoolLoss_MWh','FinalTemp_C','MaxTemp_C',...
    'PoolBalanceResidual_MWh','GasHeat_MWh','SourceUtilization','ERF_proxy'});
 fprintf('POOL_SENSITIVITY %s V=%.0f E=%.2f peakT=%.3f\n',...
    x.name,m.pool_volume_m3,m.pool_heat_MWh,m.pool_max_C);
 assert(m.pool_max_temp_screening_pass);
end
S=vertcat(outrows{:});
writetable(S,fullfile(here,'pool_volume_cover_sensitivity_2025.csv'));
assert(S.PoolHeat_MWh(2)>S.PoolHeat_MWh(1));
assert(S.PoolHeat_MWh(3)>S.PoolHeat_MWh(1));
disp('POOL_VOLUME_COVER_SENSITIVITY_PASS');
