function b=coupled_temperature_boundary_v54(s,p,E,request)
% Synthetic tank-return recirculation topology; instantaneous feasibility only.
% Unlike v53 fixed-return topology, hot inlet follows the well-mixed tank.
names={'source_in_C','source_glide_K','evaporator_approach_K','condenser_approach_K', ...
    'tank_max_C','delivery_C','charge_approach_K','discharge_approach_K', ...
    'direct_approach_K','source_capacity_MW_per_K','hot_capacity_MW_per_K', ...
    'hp_capacity_MW','cooling_factor','aux_per_compressor'};
for j=1:numel(names)
    assert(isfield(s,names{j}),'DCHR:v54:Domain','Missing boundary field.');
    scalar(s.(names{j}));
end
for name={'ambient_C','heat_capacity_MWh_per_K'},scalar(p.(name{1}));end
scalar(E);scalar(request);
assert(all([s.evaporator_approach_K s.condenser_approach_K s.charge_approach_K ...
    s.discharge_approach_K s.direct_approach_K s.source_capacity_MW_per_K ...
    s.hot_capacity_MW_per_K s.hp_capacity_MW s.aux_per_compressor E request]>=0) && ...
    s.source_glide_K>0 && s.cooling_factor>0 && s.cooling_factor<=1 && ...
    p.heat_capacity_MWh_per_K>0,'DCHR:v54:Domain','Invalid scalar domain.');
C=p.heat_capacity_MWh_per_K;Ta=p.ambient_C;T=Ta+E/C;
Te=s.source_in_C-s.source_glide_K-s.evaporator_approach_K;
floor=s.delivery_C+s.direct_approach_K;
hot=max(T+s.charge_approach_K,floor);Tc=hot+s.condenser_approach_K;
cut=s.delivery_C+s.discharge_approach_K;glide=hot-T;
assert(all([Ta T Te Tc s.source_in_C s.delivery_C]>-273.15) && ...
    Ta<cut && cut<s.tank_max_C && T<=s.tank_max_C && Tc>Te && glide>=0, ...
    'DCHR:v54:TemperatureDomain','Ordered tank/saturation domain required.');
TL=Te+273.15;lift=Tc-Te;a=s.cooling_factor*TL;cop=1+a/lift;
S=s.source_capacity_MW_per_K*s.source_glide_K;
hotbudget=s.hot_capacity_MW_per_K*glide;sourcebound=S*(1+lift/a);
[q,limiter]=min([request s.hp_capacity_MW hotbudget sourcebound]);
w=q/cop;ql=q-w;aux=s.aux_per_compressor*w;
hotflow=0;if glide>0,hotflow=q/glide;end
etaH=(lift+a)/(Tc+273.15);
assert(all(isfinite([T Te Tc glide TL lift a cop S hotbudget sourcebound q w ql aux hotflow etaH])) && ...
    a>0 && cop>1 && cop<=(Tc+273.15)/lift+32*eps(cop), ...
    'DCHR:v54:Resolution','Unresolved/overflowing derived state.');
b=struct('tank_C',T,'hot_in_C',T,'hot_out_C',hot,'evaporator_C',Te, ...
    'condenser_C',Tc,'hot_glide_K',glide,'cutoff_C',cut,'cop_compressor',cop, ...
    'heating_factor',etaH,'source_budget_MW',S,'hot_budget_MW',hotbudget, ...
    'source_bound_MW',sourcebound,'heat_MW',q,'compressor_MW',w,'source_MW',ql, ...
    'aux_rejected_MW',aux,'hot_capacity_required_MW_per_K',hotflow, ...
    'source_capacity_required_MW_per_K',ql/s.source_glide_K,'limiter',limiter, ...
    'tank_branch',T+s.charge_approach_K>=floor, ...
    'evidence_class','SYNTHETIC_TANK_RETURN_VARIABLE_FLOW_NO_UA_OR_EQUIPMENT_MAP');
end
function scalar(v)
assert(isa(v,'double')&&isreal(v)&&isscalar(v)&&isfinite(v), ...
    'DCHR:v54:Domain','Finite real double scalar required.');
end
