function a=adapt_held_schedule_v74(schedule,p,initial)
% Versioned boundary adapter for the preserved saved v73r2/v66 models.
% Columns: duration_h, physical_end_h, demand_MW, source_capacity_MW_per_K,
% HP_enable, charge_enable. Durations are authoritative binary operands;
% physical_end_h is the canonical cumsum display, never differenced for dt.
validateattributes(schedule,{'double'},{'real','finite','2d','nonempty'});
validateattributes(p,{'double'},{'real','finite','vector','numel',25});
validateattributes(initial,{'double'},{'real','finite','vector','numel',3});
assert(size(schedule,2)==6,'DCHR:v74:ScheduleShape','Six schedule columns required');
assert(all(schedule(:,1)>0)&&all(all(schedule(:,3:4)>=0))&& ...
    all(all(schedule(:,5:6)==0|schedule(:,5:6)==1)), ...
    'DCHR:v74:ScheduleDomain','Positive holds, nonnegative powers and binary flags required');
assert(isequal(schedule(:,2),cumsum(schedule(:,1)))&&all(diff([0;schedule(:,2)])>0), ...
    'DCHR:v74:PhysicalLabels','Canonical advancing cumulative labels required');
assert(initial(1)>=0&&ismember(initial(2),[0 1])&&initial(3)>=0, ...
    'DCHR:v74:InitialDomain','Invalid initial inventory, latch or age');
n=size(schedule,1);input=[ones(n,1) zeros(n,1) schedule(:,2) zeros(n,1) ...
    schedule(:,1) schedule(:,3:6) repmat(initial(:)',n,1)];
a=struct('version','0.74','saved_model_version','0.73r2','schedule',schedule, ...
    'p',p(:)','initial',initial(:)','input',input,'protocol_ticks',(0:n-1)', ...
    'timestamp_semantics','AUTHORITATIVE_BINARY_HOLD_DURATIONS_WITH_ROUNDED_CUMSUM_LABELS', ...
    'reset_semantics','INITIAL_FIELDS_USED_ON_FIRST_CALL_ONLY_NO_RESET_AT_INPUT_CHANGES');
end
