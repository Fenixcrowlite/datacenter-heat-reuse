function a=adapt_finite_stateflow_v53(s,policy,demand_MW)
% Explicit fixed refrigerant-axis scenario for preserved saved v52 algebra.
% No clipping/part-load correction; auxiliaries are external, no heat credit.
b=dchr.components.finite_temperature_boundary_v53(s);
validateattributes(demand_MW,{'double'},{'real','finite','column','nonempty','nonnegative'});
names={'dt_h','ambient_C','heat_capacity_MWh_per_K','charge_limit_MW','discharge_limit_MW', ...
    'eta_charge','eta_discharge','loss_rate_per_h','boiler_limit_MW','restart_C', ...
    'initial_energy_MWh','min_on_h','min_off_h'};
for k=1:numel(names),validateattributes(policy.(names{k}),{'double'},{'real','finite','scalar'});end
assert(s.aux_hot_fraction==0,'DCHR:v53:AuxThermalIntegration', ...
    'Saved v52 has no auxiliary thermal port; require zero hot fraction.');
assert(policy.ambient_C>-273.15 && policy.ambient_C<b.cutoff_C && ...
    b.cutoff_C<policy.restart_C && policy.restart_C<s.tank_max_C && ...
    policy.heat_capacity_MWh_per_K>0 && policy.dt_h>0 && ...
    all([policy.min_on_h policy.min_off_h]>=0), ...
    'DCHR:v53:PolicyDomain','Ordered physical tank and timer envelope required.');
C=policy.heat_capacity_MWh_per_K;
p=[policy.dt_h C*(s.tank_max_C-policy.ambient_C) policy.charge_limit_MW ...
    policy.discharge_limit_MW policy.eta_charge policy.eta_discharge policy.loss_rate_per_h ...
    C*(b.cutoff_C-policy.ambient_C) C policy.ambient_C policy.boiler_limit_MW];
% These bounds contain the predicted COP and do not clip it.
h=[b.hp_capacity_MW b.heating_factor 1+(b.cop_compressor-1)/2 b.cop_compressor+1 0 0 0 0 0];
c=[C*(policy.restart_C-policy.ambient_C) policy.min_on_h policy.min_off_h 64];
x=[repmat([b.source_budget_MW b.evaporator_C b.condenser_C],numel(demand_MW),1) ...
    demand_MW repmat(s.delivery_C,numel(demand_MW),1)];
m0=[1;0;0;0];
for k=1:size(x,1),dchr_stateflow_hp_v52(x(k,:)',policy.initial_energy_MWh,p,h,policy.dt_h);end
dchr_segment_plan_v52(x(1,:)',policy.initial_energy_MWh,p,h,policy.dt_h,m0,c);
a=struct('version','0.53','model_version','0.52','boundary_spec',s,'boundary',b,'policy',policy, ...
    'inputs',x,'p',p,'h',h,'c',c,'initial_energy_MWh',policy.initial_energy_MWh, ...
    'initial_clock',m0,'temperature_axes','FIXED_REFRIGERANT_SATURATION_WITH_EXPLICIT_VARIABLE_WATER_FLOW', ...
    'auxiliary_policy','EXTERNAL_ELECTRICITY_ALL_REJECTED_NO_DISPATCH_HEAT_CREDIT');
end
