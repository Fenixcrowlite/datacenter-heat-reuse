function [x,h,b]=stateflow_finite_boundary_v57(v,p,c)
%#codegen
% v=[v53's 16 water-boundary fields; demand]. Held per macro interval.
% Compiled validation and conversion; no host adapter authorizes these ports.
assert(all(isfinite(v)) && all(isfinite(p)) && all(isfinite(c)), ...
    'Finite boundary requires finite input and policy.');
assert(v(2)>0 && all(v([3 4 7 8 9 11 12 13 15])>=0) && ...
    v(14)>0 && v(14)<=1 && v(16)==0 && v(17)>=0, ...
    'Invalid finite boundary glide/factor/capacity/auxiliary/demand.');
sourceOut=v(1)-v(2);evap=sourceOut-v(3);
hotOut=max(v(5)+v(7),v(6)+v(9));cond=hotOut+v(4);
cutoff=v(6)+v(8);hotGlide=hotOut-v(10);
assert(all([v(1) sourceOut evap v(10) v(5) v(6) cutoff hotOut cond]>-273.15) && ...
    cutoff<v(5) && hotGlide>0 && cond>evap, ...
    'Invalid finite water/refrigerant temperature ordering.');
assert(p(9)>0 && p(10)>-273.15 && p(10)<cutoff, ...
    'Invalid finite tank ambient/heat capacity.');
% Inventory and cutoff remain fixed per run: changing these is not an input.
assert(v(5)==p(10)+p(2)/p(9) && cutoff==p(10)+p(8)/p(9) && ...
    p(8)<c(1) && c(1)<p(2), ...
    'Finite boundary cannot redefine tank capacity/cutoff/restart.');
TL=evap+273.15;TH=cond+273.15;lift=cond-evap;
eer=v(14)*TL/lift;cop=1+eer;
eta=(lift+v(14)*TL)/TH;
source=v(11)*v(2);hot=v(12)*hotGlide;cap=min(v(13),hot);
assert(all(isfinite([TL TH lift eer cop eta source hot cap])) && ...
    eer>0 && cop>1 && eta>0 && eta<=1, ...
    'Unresolved or overflowing finite boundary.');
x=[source;evap;cond;v(17);v(6)];
h=[cap eta 1+eer/2 cop+1 0 0 0 0 0];
b=[sourceOut;evap;cond;hotOut;cutoff;cop;eta;source;hot;cap;v(15);v(2);hotGlide];
end
