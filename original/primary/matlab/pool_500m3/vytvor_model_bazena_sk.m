function cesta_modelu = vytvor_model_bazena_sk()
% Vytvori samostatny spustitelny model bazena, nezasahuje do DCHR v85.
priecinok = fileparts(mfilename('fullpath'));
nazov = 'Bazen_DC_Ohrev_500m3_SK';
cesta_modelu = fullfile(priecinok,[nazov '.slx']);
if bdIsLoaded(nazov), close_system(nazov,0); end
if exist(cesta_modelu,'file'), delete(cesta_modelu); end
new_system(nazov);
open_system(nazov);
set_param(nazov,'StopTime','604800','Solver','ode4','SolverType','Fixed-step', ...
    'FixedStep','60','ReturnWorkspaceOutputs','on');
% Zdroj dodaneho tepla a prevadzkovy harmonogram.
add_block('simulink/Sources/From Workspace',[nazov '/Dostupny_tepelny_vykon'], ...
    'Position',[35 140 175 175],'VariableName','teplo_dostupne', ...
    'Interpolate','on');
add_block('simulink/Sources/From Workspace',[nazov '/Aktivita_bazena'], ...
    'Position',[35 285 175 320],'VariableName','aktivita_bazena', ...
    'Interpolate','on');
add_block('simulink/Sources/From Workspace',[nazov '/Krycia_plachta'], ...
    'Position',[35 350 175 385],'VariableName','krycia_plachta', ...
    'Interpolate','on');
add_block('simulink/Sources/Constant',[nazov '/Pozadovana_teplota'], ...
    'Position',[35 35 175 70],'Value','28');
add_block('simulink/Math Operations/Sum',[nazov '/Regulacna_odchylka'], ...
    'Position',[240 35 270 80],'Inputs','+-');
add_block('simulink/Discontinuities/Relay',[nazov '/Termostat_s_hysterezou'], ...
    'Position',[320 28 465 85], ...
    'OnSwitchValue','0.2','OffSwitchValue','-0.2', ...
    'OnOutputValue','1','OffOutputValue','0');
add_block('simulink/Math Operations/Product',[nazov '/Vykon_do_bazena'], ...
    'Position',[520 127 555 176],'Inputs','**');
add_block('simulink/Math Operations/Sum',[nazov '/Energeticka_bilancia'], ...
    'Position',[680 130 715 175],'Inputs','+-');
add_block('simulink/Math Operations/Gain',[nazov '/Tepelna_kapacita_vody'], ...
    'Position',[755 126 910 170],'Gain','1/(997*500*4182)');
add_block('simulink/Continuous/Integrator',[nazov '/Teplota_vody'], ...
    'Position',[940 124 990 169],'InitialCondition','16');
add_block('simulink/User-Defined Functions/MATLAB Function',[nazov '/Tepelne_straty'],...
    'Position',[350 272 565 385]);
rt = sfroot();
chart = rt.find('-isa','Stateflow.EMChart', ...
    'Path',[nazov '/Tepelne_straty']);
assert(~isempty(chart),'Nepodarilo sa vytvorit MATLAB Function blok.');
chart.Script = strjoin([ ...
"function [Q_straty,Q_vypar,Q_konstrukcia] = strata(T_voda,aktivita,plachta)" newline ...
"%#codegen" newline ...
"% Fyzikalne rovnice, jednotky: W, degC, kg/s, Pa/kPa." newline ...
"A=312.5; h=3; UA=800; cp=4182;" newline ...
"pvoda=0.61094*exp(17.625*T_voda/(T_voda+243.04));" newline ...
"pvzduch=0.60*0.61094*exp(17.625*29/(29+243.04));" newline ...
"mvypar=max(0,4e-5*A*(pvoda-pvzduch)*aktivita*(1-0.90*plachta));" newline ...
"Q_vypar=mvypar*2440000;" newline ...
"Q_konv=3*A*(T_voda-29)*(1-0.75*plachta);" newline ...
"Q_rad=0.95*5.670374419e-8*A*((T_voda+273.15)^4-(27+273.15)^4)*(1-0.75*plachta);" newline ...
"Q_konstrukcia=UA*(T_voda-20);" newline ...
"Q_doplnanie=mvypar*cp*(T_voda-15);" newline ...
"Q_straty=Q_vypar+Q_konv+Q_rad+Q_konstrukcia+Q_doplnanie+2000;" newline ...
"end"], newline);
% Ziskat aktualne porty po zmene MATLAB Function bloku.
set_param(nazov,'SimulationCommand','update');
add_line(nazov,'Pozadovana_teplota/1','Regulacna_odchylka/1','autorouting','on');
add_line(nazov,'Teplota_vody/1','Regulacna_odchylka/2','autorouting','on');
add_line(nazov,'Regulacna_odchylka/1','Termostat_s_hysterezou/1','autorouting','on');
add_line(nazov,'Dostupny_tepelny_vykon/1','Vykon_do_bazena/1','autorouting','on');
add_line(nazov,'Termostat_s_hysterezou/1','Vykon_do_bazena/2','autorouting','on');
add_line(nazov,'Vykon_do_bazena/1','Energeticka_bilancia/1','autorouting','on');
add_line(nazov,'Teplota_vody/1','Tepelne_straty/1','autorouting','on');
add_line(nazov,'Aktivita_bazena/1','Tepelne_straty/2','autorouting','on');
add_line(nazov,'Krycia_plachta/1','Tepelne_straty/3','autorouting','on');
add_line(nazov,'Tepelne_straty/1','Energeticka_bilancia/2','autorouting','on');
add_line(nazov,'Energeticka_bilancia/1','Tepelna_kapacita_vody/1','autorouting','on');
add_line(nazov,'Tepelna_kapacita_vody/1','Teplota_vody/1','autorouting','on');
% Monitorovanie teploty a vykonov.
zoznam = {'Zaznam_teploty','sim_teplota_vody', [1100 70 1250 100];...
          'Zaznam_ohrevu','sim_tepelny_vykon',[600 215 760 245];...
          'Zaznam_strat','sim_tepelne_straty',[640 315 800 345];...
          'Zaznam_vyparu','sim_vypar',[650 360 800 390];...
          'Zaznam_podlozia','sim_podlozie',[655 405 805 435]};
for k=1:size(zoznam,1)
 add_block('simulink/Sinks/To Workspace',[nazov '/' zoznam{k,1}], ...
    'Position',zoznam{k,3},'VariableName',zoznam{k,2}, ...
    'SaveFormat','Timeseries');
end
add_line(nazov,'Teplota_vody/1','Zaznam_teploty/1','autorouting','on');
add_line(nazov,'Vykon_do_bazena/1','Zaznam_ohrevu/1','autorouting','on');
add_line(nazov,'Tepelne_straty/1','Zaznam_strat/1','autorouting','on');
add_line(nazov,'Tepelne_straty/2','Zaznam_vyparu/1','autorouting','on');
add_line(nazov,'Tepelne_straty/3','Zaznam_podlozia/1','autorouting','on');
add_block('simulink/Sinks/Scope',[nazov '/Priebeh_teploty'], ...
    'Position',[1105 132 1150 174]);
add_line(nazov,'Teplota_vody/1','Priebeh_teploty/1','autorouting','on');
an=Simulink.Annotation(nazov, ...
  'MODEL: DATA CENTRUM -> VYMENNIK / TEPELNE CERPADLO -> BAZEN 500 m3');
an.Position=[310 5 890 20];
set_param(nazov,'SimulationCommand','update');
save_system(nazov,cesta_modelu);
close_system(nazov);
fprintf('ULOZENE: %s\n',cesta_modelu);
end
